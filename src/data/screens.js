export function formatDurationMinutes(totalMinutes) {
  if (totalMinutes == null) return '—'
  const h = Math.floor(totalMinutes / 60)
  const m = totalMinutes % 60
  if (h === 0) return `${m}m`
  if (m === 0) return `${h}h`
  return `${h}h ${m}m`
}

export function companiesFromScreens(screens = ADMIN_SCREENS) {
  return [...new Set(screens.map((s) => s.company))].sort()
}

export function countriesFromScreens(screens = ADMIN_SCREENS) {
  return [...new Set(screens.map((s) => s.country).filter(Boolean))].sort()
}
